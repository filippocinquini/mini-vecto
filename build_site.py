"""
build_site.py - turns the mission CSVs into data/missions_data.js for index.html

Why a .js file and not the CSVs directly: a page opened with a double click (file://)
cannot fetch() local files in Chrome/Edge/Safari, but it can load a <script src>.
Run this after missions.py (missions.py already calls it at the end):

    python3 build_site.py
"""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
MISSIONS = [("timber_empty", "Timber truck · empty leg"), ("timber_loaded", "Timber truck · loaded leg"),
            ("urban_bus", "Urban bus"), ("coach", "Coach")]


def col(rows, key, cast=float, nd=None):
    out = []
    for r in rows:
        v = cast(r[key])
        if nd is not None and isinstance(v, float):
            v = round(v, nd)
        out.append(v)
    return out


def main():
    summary_path = os.path.join(HERE, "mission_summary.json")
    summary = json.load(open(summary_path)) if os.path.exists(summary_path) else {}
    data = {"generated_from": "cycle_*_distance.csv, cycle_*_1Hz.csv, mission_summary.json", "missions": {}}
    for tag, label in MISSIONS:
        fd = os.path.join(HERE, f"cycle_{tag}_distance.csv")
        ft = os.path.join(HERE, f"cycle_{tag}_1Hz.csv")
        if not os.path.exists(fd):
            print(f"skip {tag}: {fd} not found")
            continue
        rows = list(csv.DictReader(open(fd)))
        # surface and road class are strings repeated per row -> dictionary-encode them
        surf_names = sorted({r["surface"] for r in rows})
        rc_names = []
        for r in rows:
            if r["road_class"] not in rc_names:
                rc_names.append(r["road_class"])
        m = {
            "label": label,
            "s": col(rows, "s_m", int),
            "vt": col(rows, "v_target_kmh", float, 1),
            "v": col(rows, "v_sim_kmh", float, 2),
            "a": col(rows, "a_sim_mps2", float, 3),
            "g": col(rows, "grade_pct", float, 2),
            "z": col(rows, "altitude_m", float, 1),
            "surf": [surf_names.index(r["surface"]) for r in rows],
            "rc": [rc_names.index(r["road_class"]) for r in rows],
            "dwell": col(rows, "stop_dwell_s", float, 1),
            "t": col(rows, "t_s", float, 1),
            "surf_names": surf_names,
            "rc_names": rc_names,
            "summary": summary.get(tag, {}),
        }
        if os.path.exists(ft):
            tr = list(csv.DictReader(open(ft)))
            m["t1"] = col(tr, "t_s", int)
            m["v1"] = col(tr, "v_kmh", float, 2)
        data["missions"][tag] = m
        print(f"{tag}: {len(rows)} distance rows" + (f", {len(m.get('t1', []))} time rows" if "t1" in m else ""))
    os.makedirs(os.path.join(HERE, "data"), exist_ok=True)
    out = os.path.join(HERE, "data", "missions_data.js")
    with open(out, "w") as f:
        f.write("// generated by build_site.py - do not edit by hand, rerun the script instead\n")
        f.write("window.MISSIONS_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {out} ({os.path.getsize(out)/1e6:.2f} MB)")


if __name__ == "__main__":
    main()
